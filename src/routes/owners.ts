import { Router, type Request, type RequestHandler, type Response } from 'express';
import { iso } from '../clock.js';
import { authenticate, getDeviceAuth } from '../middleware/auth.js';
import { mergePaths, operation } from '../openapi/operation.js';
import {
  createOwnerSchema,
  deviceTokenSchema,
  heartbeatSchema,
  ownerSchema,
  registerDeviceSchema,
} from '../schemas.js';
import { type OwnerService } from '../services/owner-service.js';
import { parse } from '../validation.js';

const ownerIdParam = { ownerId: 'Public owner id (UUID v4) generated by the app' };

export const openApiPaths = mergePaths(
  operation({
    method: 'post',
    path: '/api/v1/owners',
    tag: 'Owners & devices',
    summary: 'Create an owner',
    description: [
      'Registers an owner identity. `ownerId` and `ownerSecret` are generated by the app',
      '(see oliverlorenz/uhabits#26); the server stores only a hash of the secret.',
      'Calling it again with the same secret is a no-op (200), so the app can simply retry.',
      'Failed attempts are rate limited.',
    ].join(' '),
    auth: 'none',
    body: createOwnerSchema,
    responses: {
      201: { description: 'Owner created', schema: ownerSchema },
      200: { description: 'Owner already existed with this secret', schema: ownerSchema },
    },
    errors: {
      400: 'Invalid ownerId or ownerSecret',
      409: 'The ownerId is taken by a different secret',
    },
  }),
  operation({
    method: 'post',
    path: '/api/v1/owners/{ownerId}/devices',
    tag: 'Owners & devices',
    summary: 'Register a device',
    description: [
      'Proves the owner with `ownerSecret` and returns a new device token. Every device of the',
      'owner gets its own token, so a lost device can be revoked alone. Registering the same',
      '`deviceId` again replaces its token. Failed attempts are rate limited.',
    ].join(' '),
    auth: 'none',
    pathParams: ownerIdParam,
    body: registerDeviceSchema,
    responses: { 201: { description: 'Device token issued', schema: deviceTokenSchema } },
    errors: {
      400: 'Invalid request body',
      401: 'Wrong owner secret',
      404: 'Owner not found',
    },
  }),
  operation({
    method: 'delete',
    path: '/api/v1/owners/{ownerId}/devices/{deviceId}',
    tag: 'Owners & devices',
    summary: 'Revoke a device',
    description:
      'Revokes a device of the same owner (also the calling device itself). Its token stops working immediately.',
    auth: 'device',
    pathParams: { ...ownerIdParam, deviceId: 'Device to revoke' },
    responses: { 204: { description: 'Device revoked' } },
    errors: {
      401: 'Missing or invalid token',
      403: 'Reader tokens are read-only',
      404: 'Device not found (or owned by someone else)',
    },
  }),
  operation({
    method: 'post',
    path: '/api/v1/heartbeat',
    tag: 'Owners & devices',
    summary: 'Device heartbeat',
    description: [
      'The app sends this regularly (weekly) to every server with active shares, even without',
      'new entries. Shares of owners without heartbeat turn `inactive` after 90 days and end',
      'after 12 months. Every other request with a device token counts as well.',
    ].join(' '),
    auth: 'device',
    responses: { 200: { description: 'Heartbeat recorded', schema: heartbeatSchema } },
    errors: { 401: 'Missing or invalid token', 403: 'Reader tokens are read-only' },
  }),
);

export function createOwnersRouter(owners: OwnerService, secretLimit: RequestHandler): Router {
  const router = Router();
  const deviceAuth = authenticate(owners, 'device');

  router.post('/owners', secretLimit, (req: Request, res: Response) => {
    const body = parse(createOwnerSchema, req.body);
    const owner = owners.createOwner(body.ownerId, body.ownerSecret);
    res
      .status(owner.created ? 201 : 200)
      .json({ ownerId: owner.ownerId, createdAt: iso(owner.createdAt) });
  });

  router.post('/owners/:ownerId/devices', secretLimit, (req: Request, res: Response) => {
    const body = parse(registerDeviceSchema, req.body);
    const device = owners.registerDevice(
      String(req.params['ownerId']),
      body.ownerSecret,
      body.deviceId,
      body.name,
    );
    res.status(201).json(device);
  });

  router.delete('/owners/:ownerId/devices/:deviceId', deviceAuth, (req: Request, res: Response) => {
    owners.revokeDevice(
      getDeviceAuth(res),
      String(req.params['ownerId']),
      String(req.params['deviceId']),
    );
    res.status(204).end();
  });

  router.post('/heartbeat', deviceAuth, (_req: Request, res: Response) => {
    const beat = owners.heartbeat(getDeviceAuth(res));
    res.json({ deviceId: beat.deviceId, lastSeenAt: iso(beat.lastSeenAt) });
  });

  return router;
}
