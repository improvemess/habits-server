import type { OpenAPIV3_1 } from 'openapi-types';
import { mergePaths, toJsonSchema } from './openapi/operation.js';
import { openApiPaths as invitePagePaths } from './routes/invite-page.js';
import { openApiPaths as invitesPaths } from './routes/invites.js';
import { openApiPaths as ownersPaths } from './routes/owners.js';
import { openApiPaths as sharesPaths } from './routes/shares.js';
import { appVersion, openApiPaths as systemPaths } from './routes/system.js';
import { errorSchema } from './schemas.js';

const DESCRIPTION = `
Server for sharing single habits of [Loop Habit Tracker](https://github.com/oliverlorenz/uhabits)
with a small circle of friends. Only the owner checks a habit off; friends can only read it.
There are no accounts and no e-mail addresses.

## Flow

1. **Create the owner**: the app generates \`ownerId\` (UUID v4) and \`ownerSecret\` (256 bit)
   once and calls \`POST /api/v1/owners\`. The server stores a hash of the secret.
2. **Register the device**: with \`ownerSecret\` every device of the owner gets its own
   *device token* (\`POST /api/v1/owners/{ownerId}/devices\`). Device tokens may write.
3. **Create a share** for a habit (\`POST /api/v1/shares\`) and upload its entries
   (\`PUT /api/v1/shares/{shareId}/entries\`).
4. **Invite**: \`POST /api/v1/shares/{shareId}/invites\` returns a one-time code. The app sends
   the friend the link \`https://<server-base>/invite/<code>#k=<share-key>&v=1\`.
5. **Redeem**: the friend's app calls \`POST /api/v1/invites/{code}/redeem\` and receives a
   read-only *reader token*.
6. **Read**: \`GET /api/v1/shares/{shareId}?since=<revision>\` returns master data and the
   entries changed since the last call.

## End-to-end encryption

The share key is generated by the owner's app and only travels in the **fragment** of the invite
link, which browsers never send to a server. Master data (\`meta\`) and entries (\`data\`) are
encrypted with it (AES-256-GCM, versioned wire format) and stored by the server as opaque
base64url strings. The server only sees ids, dates and timestamps — which is all it needs to sync
and to clean up.

## Several servers

Anyone can run a server, and friends may use different ones. The app checks a server with
\`GET /.well-known/uhabits-server\` before using it; the invite link carries its server as origin.

## Tokens

All tokens are opaque bearer tokens (\`Authorization: Bearer …\`) and stored only as hashes.
Device tokens start with \`dt_\`, reader tokens with \`rt_\`. Reader tokens are strictly
read-only: every write with one is rejected with \`403\`.

## Errors

Errors are JSON: \`{ "error": "…" }\`. Endpoints that check secrets are rate limited; failed
attempts count.
`.trim();

export function buildOpenApiSpec(basePath: string): OpenAPIV3_1.Document {
  return {
    openapi: '3.1.0',
    info: {
      title: 'uhabits-server',
      version: appVersion(),
      description: DESCRIPTION,
    },
    servers: [{ url: basePath === '' ? '/' : basePath }],
    tags: [
      { name: 'Owners & devices', description: 'Owner identity and per-device tokens' },
      { name: 'Shares', description: 'Shared habits and their entries (owner devices)' },
      { name: 'Invites & subscriptions', description: 'Inviting friends and reading as a friend' },
      { name: 'System', description: 'Health, version and discovery' },
    ],
    components: {
      securitySchemes: {
        DeviceToken: {
          type: 'http',
          scheme: 'bearer',
          bearerFormat: 'dt_…',
          description:
            'Token of an owner device from `POST /api/v1/owners/{ownerId}/devices`. May read and write the shares of its owner.',
        },
        ReaderToken: {
          type: 'http',
          scheme: 'bearer',
          bearerFormat: 'rt_…',
          description:
            'Read-only token of a friend from `POST /api/v1/invites/{code}/redeem`. May only read its one share.',
        },
      },
      schemas: { Error: toJsonSchema(errorSchema, 'output') },
    },
    paths: mergePaths(systemPaths, ownersPaths, sharesPaths, invitesPaths, invitePagePaths),
  };
}
